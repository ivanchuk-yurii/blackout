create type public.truth_or_lie_states as enum('pending', 'started', 'finished');

create table public.truth_or_lie_question_pool (
  id integer primary key generated by default as identity,
  question text not null
);

create table public.truth_or_lie (
  id uuid primary key default gen_random_uuid(),
  hangout_id uuid not null references public.hangouts (id) on delete cascade,
  state public.truth_or_lie_states not null default 'pending',
  rounds smallint not null check (rounds between 1 and 100),
  created_at timestamptz not null default now()
);

create table public.truth_or_lie_members (
  game_id uuid not null references public.truth_or_lie (id) on delete cascade,
  user_id uuid not null references public.users (id),
  created_at timestamptz not null default now(),
  primary key (game_id, user_id)
);

create table public.truth_or_lie_questions (
  id uuid primary key default gen_random_uuid(),
  game_id uuid not null references public.truth_or_lie (id) on delete cascade,
  user_id uuid not null references public.users (id),
  question text not null,
  created_at timestamptz not null default now()
);

create table public.truth_or_lie_correct_answers (
  id uuid primary key references public.truth_or_lie_questions (id) on delete cascade,
  answer boolean not null
);

create table public.truth_or_lie_answers (
  question_id uuid not null references public.truth_or_lie_questions (id) on delete cascade,
  user_id uuid not null references public.users (id),
  answer boolean not null,
  created_at timestamptz not null default now(),
  primary key (question_id, user_id)
);

create function private.truth_or_lie_hangout_id (game_id uuid) returns uuid language sql stable security definer
set
  search_path = public as $$
  select g.hangout_id
  from public.truth_or_lie g
  where g.id = truth_or_lie_hangout_id.game_id;
$$;

create function private.is_truth_or_lie_member (question_id uuid) returns boolean language sql stable security definer
set
  search_path = public as $$
  select exists (
      select 1
      from public.truth_or_lie_questions q
        join public.truth_or_lie_members m on m.game_id = q.game_id
      where q.id = is_truth_or_lie_member.question_id
        and m.user_id = auth.uid ()
    );
$$;

create function private.is_question_completed (question_id uuid) returns boolean language sql stable security definer
set
  search_path = public as $$
  select (
      select count(*) - 1
      from public.truth_or_lie_questions q
        join public.truth_or_lie_members m on m.game_id = q.game_id
      where q.id = is_question_completed.question_id
    ) = (
      select count(*)
      from public.truth_or_lie_answers a
      where a.question_id = is_question_completed.question_id
    );
$$;

create function private.create_truth_or_lie_question (game_id uuid, user_id uuid) returns uuid language plpgsql security definer
set
  search_path = public as $$
declare
  new_question_id uuid;
begin
insert into
  public.truth_or_lie_questions (game_id, user_id, question)
select
  create_truth_or_lie_question.game_id,
  create_truth_or_lie_question.user_id,
  p.question
from
  public.truth_or_lie_question_pool p
order by
  random()
limit
  1
returning id into new_question_id;

insert into
  public.truth_or_lie_correct_answers (id, answer)
values
  (new_question_id, random() < 0.5);

return new_question_id;
end;
$$;

create policy "participant reads hangout truth or lie" on public.truth_or_lie for
select
  to authenticated using (private.is_hangout_participant (hangout_id));

create policy "creator creates hangout truth or lie" on public.truth_or_lie for insert to authenticated
with
  check (
    private.is_hangout_active (hangout_id)
    and private.is_hangout_creator (hangout_id)
  );

create policy "creator updates pending hangout truth or lie" on public.truth_or_lie
for update
  to authenticated using (
    private.is_hangout_creator (hangout_id)
    and state = 'pending'
  )
with
  check (private.is_hangout_creator (hangout_id));

create policy "creator deletes pending hangout truth or lie" on public.truth_or_lie for delete to authenticated using (
  private.is_hangout_creator (hangout_id)
  and state = 'pending'
);

create policy "participant reads truth or lie members" on public.truth_or_lie_members for
select
  to authenticated using (
    private.is_hangout_participant (private.truth_or_lie_hangout_id (game_id))
  );

create policy "user joins pending truth or lie" on public.truth_or_lie_members for insert to authenticated
with
  check (
    (
      select
        auth.uid ()
    ) = user_id
    and private.is_hangout_participant (private.truth_or_lie_hangout_id (game_id))
    and exists (
      select
        1
      from
        public.truth_or_lie g
      where
        (
          g.id = truth_or_lie_members.game_id
          and g.state = 'pending'
        )
    )
  );

create policy "user leaves pending truth or lie" on public.truth_or_lie_members for delete to authenticated using (
  (
    select
      auth.uid ()
  ) = user_id
);

create policy "participant reads hangout truth or lie questions" on public.truth_or_lie_questions for
select
  to authenticated using (true);

create policy "user reads completed truth or lie correct answers" on public.truth_or_lie_correct_answers for
select
  to authenticated using (private.is_question_completed (id));

create policy "author reads own truth or lie correct answer" on public.truth_or_lie_correct_answers for
select
  to authenticated using (
    exists (
      select
        1
      from
        public.truth_or_lie_questions q
      where
        (
          q.id = truth_or_lie_correct_answers.id
          and q.user_id = (
            select
              auth.uid ()
          )
        )
    )
  );

create policy "member reads truth or lie answers" on public.truth_or_lie_answers for
select
  to authenticated using (private.is_truth_or_lie_member (question_id));

create policy "member answers others truth or lie question" on public.truth_or_lie_answers for insert to authenticated
with
  check (
    (
      select
        auth.uid ()
    ) = user_id
    and exists (
      select
        1
      from
        public.truth_or_lie_questions q
      where
        (
          q.id = truth_or_lie_answers.question_id
          and q.user_id <> truth_or_lie_answers.user_id
        )
    )
    and private.is_truth_or_lie_member (question_id)
  );

create or replace function private.advance_truth_or_lie () returns trigger language plpgsql security definer
set
  search_path = public as $$
declare
  current_game_id uuid;
  next_user_id uuid;
  question_count smallint;
  member_count smallint;
  total_rounds smallint;
begin

perform pg_advisory_xact_lock (hashtextextended (new.question_id::text, 0));

if not private.is_question_completed (new.question_id) then
  return null;
end if;

select q.game_id into current_game_id
from public.truth_or_lie_questions q
where q.id = new.question_id;

select g.rounds into total_rounds
from public.truth_or_lie g
where g.id = current_game_id;

select count(*) into question_count
from public.truth_or_lie_questions q
where q.game_id = current_game_id;

select count(*) into member_count
from public.truth_or_lie_members m
where m.game_id = current_game_id;

if question_count / member_count = total_rounds then
  update public.truth_or_lie
  set state = 'finished'
  where id = current_game_id;

  return null;
end if;

with ordered as (
  select
    m.user_id,
    row_number() over (order by m.created_at, m.user_id) as pos,
    count(*) over () as total
  from public.truth_or_lie_members m
  where m.game_id = current_game_id
),
last_author as (
  select q.user_id
  from public.truth_or_lie_questions q
  where q.game_id = current_game_id
  order by q.created_at desc
  limit 1
)
select o.user_id into next_user_id
from ordered o
where o.pos = (
    select (p.pos % p.total) + 1
    from ordered p
    join last_author a using (user_id)
  );

if next_user_id is not null then
  perform private.create_truth_or_lie_question (current_game_id, next_user_id);
end if;

return null;
end;
$$;

create trigger advance_truth_or_lie_on_insert
after insert on public.truth_or_lie_answers for each row
execute function private.advance_truth_or_lie ();

create or replace function private.start_truth_or_lie () returns trigger language plpgsql security definer
set
  search_path = public as $$
declare
  first_user_id uuid;
begin
select m.user_id into first_user_id
from public.truth_or_lie_members m
where m.game_id = new.id
order by m.created_at, m.user_id
limit 1;

if first_user_id is not null then
  perform private.create_truth_or_lie_question (new.id, first_user_id);
end if;

return null;
end;
$$;

create trigger start_truth_or_lie_on_update
after update on public.truth_or_lie for each row when (
  old.state = 'pending'
  and new.state = 'started'
)
execute function private.start_truth_or_lie ();

